#!/usr/bin/env bash
# Generate the audio compose override. Runs on the HOST as initializeCommand, before
# anything is built, because compose itself cannot branch on what the host provides.
#
# Claude Code's /voice records through SoX's `rec`, which needs a PulseAudio server.
# VS Code forwards X11 and Wayland into a devcontainer but never audio, so the socket
# has to be bind-mounted. WSL2 hosts have one (WSLg); most others do not, and naming a
# bind source that is absent fails the container start -- hence the override, which is
# empty when no socket is found.
#
# Set VOICE_PULSE_SOCKET to point this at a socket the probe below does not know.
set -euo pipefail

cd "$(dirname "$0")/.."

OVERRIDE=docker-compose.audio.yml
# WSLg's server. Anonymous auth, so mounting the socket is all it takes.
WSLG_SOCKET=/mnt/wslg/PulseServer

socket=${VOICE_PULSE_SOCKET:-}
if [[ -z $socket && -S $WSLG_SOCKET ]]; then
  socket=$WSLG_SOCKET
fi

# Written every run, so a host that gains or loses its socket is picked up on rebuild.
if [[ -n $socket && -S $socket ]]; then
  cat > "$OVERRIDE" <<YAML
# Generated by scripts/detect-audio.sh -- do not edit, and do not commit.
# Host PulseAudio socket found, so /voice can record.
services:
  dev:
    environment:
      PULSE_SERVER: unix:/mnt/wslg/PulseServer
    volumes:
      - $socket:/mnt/wslg/PulseServer
YAML
  echo "detect-audio: mounting $socket for voice input"
else
  cat > "$OVERRIDE" <<'YAML'
# Generated by scripts/detect-audio.sh -- do not edit, and do not commit.
# No host PulseAudio socket found, so /voice will report no recorder. Nothing else
# is affected.
services:
  dev: {}
YAML
  if [[ -n $socket ]]; then
    echo "detect-audio: VOICE_PULSE_SOCKET=$socket is not a socket; voice input disabled" >&2
  else
    echo "detect-audio: no host PulseAudio socket; voice input disabled"
  fi
fi
