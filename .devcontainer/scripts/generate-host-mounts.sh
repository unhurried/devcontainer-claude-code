#!/usr/bin/env bash
# Write docker-compose.mounts.yml: one bind mount at /workspaces/mnt/<basename> per
# HOST_MOUNTS entry (see .env.example). Runs on the host as initializeCommand, before
# compose reads the file, so a bad entry stops the start instead of mounting nothing.
#
# Usage: generate-host-mounts.sh [output]  (default: ../docker-compose.mounts.yml)
# HOST_MOUNTS comes from the environment if set, else from ENV_FILE (default ../.env),
# the same precedence compose applies to .env.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEVCONTAINER_DIR="$(dirname "$HERE")"
ENV_FILE="${ENV_FILE:-$DEVCONTAINER_DIR/.env}"
OUT="${1:-$DEVCONTAINER_DIR/docker-compose.mounts.yml}"
TARGET_ROOT=/workspaces/mnt

die() {
    printf 'generate-host-mounts: %s\n' "$*" >&2
    exit 1
}

# Value of HOST_MOUNTS in a dotenv file (last assignment wins). Parsed, not sourced:
# .env is compose's format, not shell.
read_env_file() {
    local line value=
    [ -f "$1" ] || return 0
    while IFS= read -r line || [ -n "$line" ]; do
        line="${line%$'\r'}"
        [[ $line =~ ^[[:space:]]*HOST_MOUNTS[[:space:]]*=(.*)$ ]] || continue
        value="${BASH_REMATCH[1]}"
        value="${value#"${value%%[![:space:]]*}"}"
        if [[ $value =~ ^\"(.*)\"[[:space:]]*(#.*)?$ ]] || [[ $value =~ ^\'(.*)\'[[:space:]]*(#.*)?$ ]]; then
            value="${BASH_REMATCH[1]}"
        else
            # Unquoted: a " #" starts a comment, as in compose.
            value="${value%%[[:space:]]#*}"
            value="${value%"${value##*[![:space:]]}"}"
        fi
    done <"$1"
    printf '%s' "$value"
}

# Double-quoted YAML scalar. $ is doubled because compose interpolates every file.
yaml_quote() {
    local s="$1"
    s="${s//\\/\\\\}"
    s="${s//\"/\\\"}"
    s="${s//\$/\$\$}"
    printf '"%s"' "$s"
}

if [ -n "${HOST_MOUNTS+set}" ]; then
    spec="$HOST_MOUNTS"
else
    spec="$(read_env_file "$ENV_FILE")"
fi

declare -A seen=()
order=()
volumes=

# Newlines separate entries too, for a multi-line HOST_MOUNTS in the environment.
IFS=';' read -r -a entries <<<"${spec//$'\n'/;}"
for entry in "${entries[@]}"; do
    entry="${entry#"${entry%%[![:space:]]*}"}"
    entry="${entry%"${entry##*[![:space:]]}"}"
    [ -n "$entry" ] || continue

    read_only=false
    if [[ $entry == *:ro ]]; then
        read_only=true
        entry="${entry%:ro}"
    fi
    src="$entry"
    while [[ $src == */ && $src != / ]]; do src="${src%/}"; done

    [[ $src == /* ]] || die "not an absolute path: '$src'"
    ! [[ $src =~ [[:cntrl:]] ]] || die "control character in path: '$src'"
    [ -d "$src" ] || die "not an existing directory: '$src'"

    name="${src##*/}"
    [ -n "$name" ] || die "cannot mount '/': no name for it under $TARGET_ROOT"
    [[ $name != .* ]] || die "name '$name' (from '$src') starts with '.'"
    [ -z "${seen[$name]+set}" ] \
        || die "'$src' and '${seen[$name]}' both mount at $TARGET_ROOT/$name"
    seen[$name]="$src"
    order+=("$name")

    volumes+="      - type: bind
        source: $(yaml_quote "$src")
        target: $(yaml_quote "$TARGET_ROOT/$name")
        read_only: $read_only
        bind:
          create_host_path: false
"
done

tmp="$(mktemp "$OUT.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
{
    printf '# Generated by .devcontainer/scripts/generate-host-mounts.sh from HOST_MOUNTS.\n'
    printf '# Do not edit; it is rewritten on every container start.\n'
    printf 'services:\n'
    if [ -n "$volumes" ]; then
        printf '  dev:\n    volumes:\n%s' "$volumes"
    else
        printf '  dev: {}\n'
    fi
} >"$tmp"
chmod 644 "$tmp"
mv "$tmp" "$OUT"
trap - EXIT

for name in "${order[@]}"; do
    printf 'generate-host-mounts: %s -> %s/%s\n' "${seen[$name]}" "$TARGET_ROOT" "$name"
done
